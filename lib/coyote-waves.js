/** 按名字找波形（支持「呼吸」「挑逗1」这类原名，忽略大小写与空格）。 */
export function findWaveform(name) {
  const want = String(name ?? '').trim().toLowerCase().replace(/\s+/g, '');
  if (!want) return null;
  return COYOTE_WAVES.find((w) => w.name.toLowerCase().replace(/\s+/g, '') === want) || null;
}

/** 给模型看的波形清单（一行一个名字 + 帧数）。 */
export function waveformListText() {
  return COYOTE_WAVES.map((w) => `${w.name}（${(w.frames.length * 0.1).toFixed(1)}s）`).join('、');
}
